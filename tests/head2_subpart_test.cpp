        CAPTURE( child );
        detached_ptr<item> c = item::spawn( itype_id( child ) );
        detached_ptr<item> p = item::spawn( itype_id( parent ) );
        CHECK( c->get_coverage( bodypart_id( "head" ) ) == p->get_coverage( bodypart_id( "head" ) ) );
