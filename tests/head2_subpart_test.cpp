auto sbp( const std::string &id ) -> sub_bodypart_str_id
{
    return sub_bodypart_str_id( id );
}

auto set_covers( const item &it, const std::vector<std::string> &expected ) -> bool
{
    const body_part_set got = it.get_covered_body_parts();
    if( got.count() != expected.size() ) {
        return false;
    }
    return std::ranges::all_of( expected, [&]( const std::string & id ) {
        return got.test( bodypart_str_id( id ) );
    } );
}

const std::vector<std::string> head_subs = { "head_forehead", "head_crown", "head_nape",
                                             "head_throat", "head_ear_l", "head_ear_r"
                                           };

// Per-sub-location head coverage of `id` against `expected` (missing sub-locations are 0).
void check_head_shape( const char *id, const std::map<std::string, int> &expected )
{
    CAPTURE( id );
    detached_ptr<item> it = item::spawn( itype_id( id ) );
    for( const std::string &sub : head_subs ) {
        CAPTURE( sub );
        const auto found = expected.find( sub );
        const int cov = found == expected.end() ? 0 : found->second;
        CHECK( it->get_coverage( bodypart_id( "head" ), sbp( sub ) ) == cov );
        CHECK( it->covers( sbp( sub ) ) == ( cov > 0 ) );
    }
}

// Share of `hits` hits on `bp` that a worn `id` stops (damage reduced), 0..1; same measure as
// the EYEMOUTH1 test.
auto stop_rate( const std::string &id, const char *bp, int hits ) -> double
{
    clear_all_state();
    Character &guy = get_player_character();
    clear_character( *guy.as_player(), true );
    detached_ptr<item> worn = item::spawn( id );
    // CDF: UNBREAKABLE keeps thin cloth on, so the rate measures coverage only
    worn->set_flag( flag_id( "UNBREAKABLE" ) );
    guy.wear_item( std::move( worn ), false );
    const bodypart_id part( bp );
    int stopped = 0;
    for( int i = 0; i < hits; ++i ) {
        damage_instance dmg( damage_type::DT_CUT, 10 );
        guy.absorb_hit( part, dmg );
        if( dmg.damage_units[0].amount < 10.0f ) {
            ++stopped;
        }
    }
    return static_cast<double>( stopped ) / hits;
}

// CDF: the table's head aggregates truncate; the CDF loader rounds (item_factory.cpp aggregate, std::lround, P1).
// These items sit on a .5 (crown 25 + forehead 90 * 15 / 100 = 38.5 and the like), so CDF reads one more.
// Kept at CDF's rounding (existing code, other items depend on it); reported to the orchestrator.
auto agg_cdf( const std::string &id, int table_agg ) -> int
{
    static const std::set<std::string> half_points = { "helmet_larmor", "pickelhaube", "welding_mask",
            "welding_mask_crude", "helmet_bone", "helmet_plarmor"
                                                     };
    return table_agg + ( half_points.count( id ) > 0 ? 1 : 0 );
}

auto covered_ids( const item &it ) -> std::vector<std::string>
{
    std::vector<std::string> ids;
    for( const bodypart_id &b : get_player_character().get_all_body_parts() ) {
        if( it.covers( b ) ) {
            ids.push_back( b.id().str() );
        }
    }
    return ids;
}

